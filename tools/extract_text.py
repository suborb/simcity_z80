#!/usr/bin/env python3
"""Generate ui/text.h and ui/text.c (tool names, advisor messages, month names) from the
Spectrum game's own text tables, by assembling disassembly/sim_game.asm.

  usage: tools/extract_text.py    (run from the repository root; needs z80asm)
"""
import os, re, shutil, subprocess, sys, tempfile

ROOT = os.getcwd()
Z80ASM = 'z88dk-z80asm'
ORG = 23323


def main():
    tmp = tempfile.mkdtemp()
    try:
        for d in ('assets', 'disassembly'):
            shutil.copytree(os.path.join(ROOT, d), os.path.join(tmp, d),
                            ignore=None if d == 'assets' else shutil.ignore_patterns('*.bin', '*.o', '*.map', '*.sym'))
        subprocess.run([Z80ASM, '-b', '-m', 'disassembly/sim_game.asm'], cwd=tmp, check=True, capture_output=True)
        image = open(os.path.join(tmp, 'disassembly/sim_game.bin'), 'rb').read()
        syms = {}
        for line in open(os.path.join(tmp, 'disassembly/sim_game.map')):
            m = re.match(r'(\S+)\s*=\s*\$([0-9A-Fa-f]+)', line)
            if m:
                syms[m.group(1)] = int(m.group(2), 16)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    def words(start, end):
        out, cur = [], bytearray()
        for b in image[start - ORG:end - ORG]:
            if b >= 128:
                cur.append(b & 127)
                out.append(cur.decode('latin1'))
                cur = bytearray()
            else:
                cur.append(b)
        return out

    table = words(syms['text_table'], syms['print_selected_tool_name'])
    # text_months is 12 words
    months, cur = [], bytearray()
    for b in image[syms['text_months'] - ORG:]:
        if b >= 128:
            cur.append(b & 127)
            months.append(cur.decode('latin1'))
            cur = bytearray()
            if len(months) == 12:
                break
        else:
            cur.append(b)

    def c(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

    alerts = table[23:]
    with open('ui/text.h', 'w') as f:
        f.write('/* Generated by tools/extract_text.py from the Spectrum game - do not edit. */\n')
        f.write('#ifndef TEXT_H\n#define TEXT_H\n\n')
        f.write('/* Tool names with their prices, indexed by tool number 0..13 */\n')
        f.write('extern const char *const text_tools[14];\n')
        f.write('extern const char *const text_levels[3];\n')
        f.write('extern const char *const text_city_class[6];\n')
        f.write('/* Advisor messages: index = V_alertmessage (0 = none) */\n')
        f.write('extern const char *const text_alerts[%d];\n' % len(alerts))
        f.write('extern const char *const text_months[12];\n\n')
        f.write('#endif\n')
    with open('ui/text.c', 'w') as f:
        f.write('/* Generated by tools/extract_text.py from the Spectrum game - do not edit. */\n')
        f.write('#include "text.h"\n\n')
        f.write('const char *const text_tools[14] = {\n')
        f.write(',\n'.join('    ' + c(s) for s in table[:14]) + '\n};\n\n')
        f.write('const char *const text_levels[3] = { %s };\n\n' % ', '.join(c(s) for s in table[14:17]))
        f.write('const char *const text_city_class[6] = { %s };\n\n' % ', '.join(c(s) for s in table[17:23]))
        f.write('const char *const text_alerts[%d] = {\n' % len(alerts))
        f.write(',\n'.join('    ' + c(s.strip()) for s in alerts) + '\n};\n\n')
        f.write('const char *const text_months[12] = { %s };\n' % ', '.join(c(s) for s in months))
    print('ui/text.h, ui/text.c:', len(table), 'strings,', len(months), 'months')


if __name__ == '__main__':
    main()

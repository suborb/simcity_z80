#!/usr/bin/env python3
"""Assemble the FP-1100's sub-CPU program and its loader (target/fp1100/sub.s.in, loader.s.in).

  tools/build_fp1100_sub.py OUTDIR      -> OUTDIR/sub.bin, loader.bin, sub.inc (the command bytes for the Z80 side's assembler)
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
sys.path.insert(0, here)
from asm7801 import Asm

BASE = 0x9000                   # the program: the red plane's spare VRAM, one page for the JB dispatch (the commands' entry points)
BASE2 = 0x9100                  # the second page: long commands' bodies, which fp_boot sends
LOADER = 0x3A60                 # where the ROM's "run" command ($6B) executes: blue plane, cell (4, 21)
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'build', 'fp1100')
os.makedirs(out, exist_ok=True)
a = Asm(os.path.join(here, 'asm7801_ops.json'))
src = open(os.path.join(root, 'target', 'fp1100', 'sub.s.in')).read().replace('@BASE@', '$%04X' % BASE).replace('@PAGE@', '$%02X' % (BASE >> 8)).replace('@BASE2@', '$%04X' % BASE2)
both, labels = a.assemble(src, BASE)
sub, sub2 = both[:labels['P1End'] - BASE], both[256:]
assert len(sub) <= 256 and labels['KeysBody'] == BASE2
sub2 = sub2.ljust(-(-len(sub2) // 8) * 8, b'\0')                  # (fp_boot sends it 8 bytes at a time)
open(os.path.join(out, 'sub.bin'), 'wb').write(sub)
open(os.path.join(out, 'sub2.bin'), 'wb').write(sub2)
lsrc = open(os.path.join(root, 'target', 'fp1100', 'loader.s.in')).read()
lsrc = lsrc.replace('@BASE@', '$%04X' % BASE).replace('@SUBLEN@', str(len(sub))).replace('@SUBLEN1@', str(len(sub) - 1))
loader, _ = a.assemble(lsrc, LOADER)
assert len(loader) <= 40, len(loader)       # five "define character" blocks
open(os.path.join(out, 'loader.bin'), 'wb').write(loader.ljust(40, b'\0'))
with open(os.path.join(out, 'sub.inc'), 'w') as f:
    f.write('; generated by tools/build_fp1100_sub.py\nDEFC SUB_SIZE = %d\n' % len(sub))
    f.write('DEFC SUB2_SIZE = %d\n' % len(sub2))
    for n in ('Bank', 'Addr', 'Pat', 'Cell', 'Ovl', 'Tiles', 'Inv', 'Keys', 'Tick', 'Fill', 'Text', 'Mini', 'Mini2'):
        f.write('DEFC SUB_%s = $%02X\n' % (n.upper(), labels[n] & 255))
print('fp1100 sub program: %d of 256 bytes, loader %d of 40' % (len(sub), len(loader)))

#!/usr/bin/env python3
"""Generate target/spc1500/keytab.inc from MAME's SPC-1500 keyboard matrix (src/mame/samsung/spc1500.cpp, ports LINE.0-9: row n is read at I/O port $1900 + n, bit set = key down).
Each key gives the code the game's plat_key() returns: the lower case ASCII of the key, Space 32, Return 13, Esc 27, Backspace 8, the cursor keys 9 right, 8 left,
11 up, 10 down; the others 0.  usage: tools/spc1500_keys.py [spc1500.cpp] > target/spc1500/keytab.inc"""
import re, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Projects/mame/src/mame/samsung/spc1500.cpp')
text = open(src, encoding='utf-8', errors='replace').read()
rows = {}
cur = None
for line in text.split('\n'):
    m = re.search(r'PORT_START\("LINE\.(\d)"\)', line)
    if m: cur = int(m.group(1)); rows[cur] = {}; continue
    if cur is None: continue
    if 'PORT_START' in line: cur = None; continue
    m = re.search(r'PORT_BIT\(0x([0-9a-f]+), IP_ACTIVE_HIGH, (\w+)\)(.*)', line)
    if not m: continue
    bit = int(m.group(1), 16); kind = m.group(2); rest = m.group(3)
    if kind != 'IPT_KEYBOARD': continue
    name = re.search(r'PORT_NAME\((.*?)\)\s+PORT_CODE', rest)
    name = name.group(1) if name else ''
    chars = re.findall(r"PORT_CHAR\(('(?:\\.|[^'])+'|0x[0-9a-f]+|\d+|UCHAR_\w+(?:\(\w+\))?)\)", rest)
    code = 0
    if 'UTF8_UP' in name: code = 11
    elif name == '"Right"': code = 9
    elif name == '"Left"': code = 8
    elif name == '"Down"': code = 10
    elif name == '"Return"': code = 13
    elif name == '"Space"': code = 32
    elif name == '"ESC"': code = 27
    elif name == '"Backspace"': code = 8
    elif name == '"Tab"': code = 0                    # (9 is the cursor right)
    elif chars:
        c = chars[0]
        if c.startswith("'"):
            code = ord(c[1:-1].encode().decode('unicode_escape'))
            if chr(code).isalpha(): code = ord(chr(code).lower())
    if code >= 128: code = 0
    rows[cur][bit] = (code, name)
print('; Generated by tools/spc1500_keys.py from MAME: row n is read at I/O port $1900 + n, bit set = key down; the code plat_key returns for each of the bits 0 to 7 (0: none)')
for r in range(10):
    codes = [rows[r].get(1 << b, (0, ''))[0] for b in range(8)]
    names = ' '.join((rows[r].get(1 << b, (0, ''))[1].strip('"') or '-').replace(' ', '') for b in range(8))
    print('\tdefb\t%s\t; %d: %s' % (','.join('%3d' % c for c in codes), r, names))
